#!/usr/bin/env node
// Regenerates the frontend's API contracts from the backend (the source of truth).
//
//   pnpm gen:api          write packages/shared-types/src/{api.gen.ts,taxonomy.gen.ts}
//   pnpm check:api        fail if the committed files are stale (used in CI)
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(import.meta.dirname, "..");
const backend = join(root, "apps/backend");
const outDir = join(root, "packages/shared-types/src");
const check = process.argv.includes("--check");

const tmp = mkdtempSync(join(tmpdir(), "mirra-contracts-"));
execFileSync("uv", ["run", "--project", backend, "python", "-m", "mirra.export", tmp], {
  cwd: backend,
  stdio: ["ignore", "inherit", "inherit"],
});

const spec = JSON.parse(readFileSync(join(tmp, "openapi.json"), "utf8"));
const header =
  "// GENERATED by scripts/gen-api-types.mjs from the FastAPI OpenAPI schema. Do not edit.\n" +
  "// Run `pnpm gen:api` after changing backend schemas.\n\n";
const ts = header + astToString(await openapiTS(spec, { alphabetize: true }));
const taxonomyJson = readFileSync(join(tmp, "taxonomy.json"), "utf8").trim();
const taxonomy =
  "// GENERATED by scripts/gen-api-types.mjs from mirra.core.taxonomy. Do not edit.\n\n" +
  `export const taxonomyData = ${taxonomyJson} as const;\n`;

const outputs = [
  [join(outDir, "api.gen.ts"), ts],
  [join(outDir, "taxonomy.gen.ts"), taxonomy],
];

let stale = false;
for (const [file, content] of outputs) {
  const current = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (current === content) continue;
  if (check) {
    console.error(`stale: ${file.replace(root + "/", "")}`);
    stale = true;
  } else {
    writeFileSync(file, content);
    console.log(`wrote ${file.replace(root + "/", "")}`);
  }
}
if (stale) {
  console.error("API contracts are out of date. Run `pnpm gen:api` and commit the result.");
  process.exit(1);
}
if (check) console.log("API contracts are up to date.");
